import type { Block } from "@bytecat/sb3";
import { describe, expect, it } from "vitest";
import { compileProject, load, toModule, toScript } from "../src/index.js";
import { block, project, target } from "./helpers.js";

function script(...ops: [string, Partial<Block>?][]): Record<string, Block> {
  const blocks: Record<string, Block> = { hat: block("event_whenflagclicked", { topLevel: true, next: "b0" }) };
  ops.forEach(([op, extra], i) => {
    blocks[`b${i}`] = block(op, { next: i + 1 < ops.length ? `b${i + 1}` : null, ...extra });
  });
  return blocks;
}

describe("compileProject", () => {
  it("emits a hat per script", () => {
    const { code, warnings } = compileProject(project(target(script(["motion_ifonedgebounce"]))));
    expect(warnings).toEqual([]);
    expect(code).toContain('kind: "flag"');
    expect(code).toContain("bounce(rt, t);");
  });

  describe("imports", () => {
    it("name exactly the runtime functions the code calls, by module", () => {
      const blocks = script(
        ["motion_ifonedgebounce"],
        ["motion_movesteps", { inputs: { STEPS: [1, [4, "10"]] } }],
        ["control_wait", { inputs: { DURATION: [1, [5, "1"]] } }],
      );
      expect(compileProject(project(target(blocks))).imports).toEqual([
        { from: "@bytecat/runtime/control", names: ["wait"] },
        { from: "@bytecat/runtime/motion", names: ["bounce", "move"] },
      ]);
    });

    it("leave out what a block declares but did not emit", () => {
      // "go to back" declares goToFront too, but only calls goToBack.
      const blocks = script(["looks_gotofrontback", { fields: { FRONT_BACK: ["back"] } }]);
      expect(compileProject(project(target(blocks))).imports).toEqual([{ from: "@bytecat/runtime/looks", names: ["goToBack"] }]);
    });

    it("include a code generator helper only where the code calls it", () => {
      const say = (input: unknown) => script(["looks_say", { inputs: { MESSAGE: input as never } }]);
      const lists = { l1: ["items", ["a"]] as [string, string[]] };
      // A list dropped into an input is the one place listContents is called.
      const withList = compileProject(project(target(say([3, [13, "items", "l1"], [10, ""]]), { lists })));
      expect(withList.imports).toContainEqual({ from: "@bytecat/runtime/ops", names: ["listContents"] });
      const plain = compileProject(project(target(say([1, [10, "hi"]]), { lists })));
      expect(plain.imports).toEqual([{ from: "@bytecat/runtime/looks", names: ["say"] }]);
    });

    it("are bound by toModule, toScript and load", () => {
      const result = compileProject(project(target(script(["motion_ifonedgebounce"]))));
      expect(toModule(result)).toMatch(/^\/\/ Generated by Bytecat\. Do not edit\.\nimport \{ bounce \} from "@bytecat\/runtime\/motion";\n\nexport default function \(rt\) \{\n/);
      expect(toScript(result)).toContain('const { bounce } = modules["@bytecat/runtime/motion"];');
      expect(typeof load(result)).toBe("function");
      expect(() => load({ ...result, imports: [{ from: "./missing.js", names: ["x"] }] })).toThrow("pass that module to load()");
      expect(() => load({ ...result, imports: [{ from: "@bytecat/runtime/motion", names: ["nope"] }] })).toThrow("does not export");
    });
  });

  it("reports unsupported statements and reporters once, sorted", () => {
    const blocks = script(["sound_play"], ["sound_play"], ["looks_seteffectto"]);
    const { code, warnings } = compileProject(project(target(blocks)));
    expect(warnings).toEqual(["looks_seteffectto", "sound_play"]);
    expect(code).toContain("/* unsupported: sound_play */");
  });

  it("ignores opcodes that name Object.prototype members", () => {
    const { warnings } = compileProject(project(target(script(["constructor"]))));
    expect(warnings).toEqual(["constructor"]);
  });

  it("tells the runtime which hats do not restart a running script", () => {
    const blocks = {
      key: block("event_whenkeypressed", { topLevel: true, fields: { KEY_OPTION: ["Space", null] } }),
      flag: block("event_whenflagclicked", { topLevel: true }),
    };
    const { code } = compileProject(project(target(blocks)));
    expect(code).toContain('{ target: 1, kind: "key", arg: "space", restart: false, fn: function* (t, th) {');
    expect(code).toContain('{ target: 1, kind: "flag", fn: function* (t, th) {');
  });

  it("warns about hats it cannot start", () => {
    const blocks = { hat: block("event_whenbackdropswitchesto", { topLevel: true }) };
    expect(compileProject(project(target(blocks))).warnings).toEqual(["event_whenbackdropswitchesto"]);
  });

  it("passes numeric literals as numbers, but keeps a literal that names a costume as text", () => {
    const set = (value: string): [string, Partial<Block>] => [
      "data_setvariableto",
      { inputs: { VALUE: [1, [10, value]] }, fields: { VARIABLE: ["v", "var_0"] } },
    ];
    const blocks = script(set("1"), set("1.0"), set("2"), [
      "looks_switchcostumeto",
      { inputs: { COSTUME: [1, [10, "1"]] } },
    ]);
    const sprite = target(blocks, { variables: { var_0: ["v", 0] }, costumes: [{ name: "2" }] as never });
    const { code } = compileProject(project(sprite));
    expect(code).toContain('t.v["var_0"] = 1;');
    expect(code).toContain('t.v["var_0"] = "1.0";');
    expect(code).toContain('t.v["var_0"] = "2";');
    expect(code).toContain('switchCostume(rt, t, "1");');
  });

  describe("custom reporters", () => {
    // A sprite whose flag script calls a reporter in a loop; the reporter adds to `x` and returns it.
    const reporterProject = () => {
      const mutation = { tagName: "mutation", children: [], proccode: "bump", argumentids: "[]", argumentnames: "[]", warp: "true" };
      const blocks: Record<string, Block> = {
        hat: block("event_whenflagclicked", { topLevel: true, next: "loop" }),
        loop: block("control_repeat", { inputs: { TIMES: [1, [4, "3"]], SUBSTACK: [2, "change"] } }),
        change: block("data_changevariableby", { fields: { VARIABLE: ["x", "x"] }, inputs: { VALUE: [3, "call", [4, "1"]] } }),
        call: block("procedures_call", { mutation: mutation as never }),
        def: block("procedures_definition", { topLevel: true, next: "inc", inputs: { custom_block: [1, "proto"] } }),
        proto: block("procedures_prototype", { mutation: mutation as never }),
        inc: block("data_changevariableby", { fields: { VARIABLE: ["x", "x"] }, inputs: { VALUE: [1, [4, "1"]] }, next: "ret" }),
        ret: block("procedures_return", { inputs: { VALUE: [3, [12, "x", "x"], [10, ""]] } }),
      };
      return project(target(blocks, { variables: { x: ["x", 0] } }));
    };

    it("store the caller's locals before a call in an expression and reload them after", () => {
      const { code } = compileProject(reporterProject());
      expect(code).toContain('v0 = v0 + (t.v["x"] = v0, ret = p1_0(t, th), v0 = t.v["x"], ret);');
      expect(code).toContain("let ret;");
      // Every return is a number, so the caller adds without a cast.
      expect(code).not.toContain("toNum(");
    });

    it('report "" when no return runs, and widen the return type with it', () => {
      const p = reporterProject();
      delete p.targets[1]!.blocks.ret;
      p.targets[1]!.blocks.inc!.next = null;
      const { code } = compileProject(p);
      expect(code).toMatch(/function p1_0\(t, th\) \{\n {2}t\.v\["x"\] = t\.v\["x"\] \+ 1;\n {2}return "";\n\}/);
      expect(code).toContain("toNum(");
    });
  });

  it("is deterministic", () => {
    const p = project(target(script(["motion_ifonedgebounce"])));
    expect(compileProject(p).code).toBe(compileProject(p).code);
  });
});
