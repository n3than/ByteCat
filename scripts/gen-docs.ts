// Regenerates the builtin reference tables in docs/pseudocode.md from packages/pseudo/src/builtins.ts,
// and docs/blocks.md from the extension specs in packages/compiler/src/extensions/.
// Run `pnpm run docs` after changing either; `pnpm test` fails while a doc is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BUILTIN_EXTENSIONS, type BlockSpec, type Extension } from "../packages/compiler/src/extensions/index.ts";
import { REPORTERS, STATEMENTS, type Builtin, type Slot } from "../packages/pseudo/src/builtins.ts";

const DOC = join(import.meta.dirname, "..", "docs", "pseudocode.md");
export const BLOCKS_DOC = join(import.meta.dirname, "..", "docs", "blocks.md");
const BEGIN = "<!-- builtins:begin (generated by `pnpm run docs`, do not edit by hand) -->";
const END = "<!-- builtins:end -->";

function argName(slot: Slot): string {
  switch (slot.kind) {
    case "value":
    case "bool":
    case "menu":
    case "broadcast":
      return slot.input.toLowerCase();
    case "field":
      return slot.field.toLowerCase();
  }
}

function rows(table: Record<string, Builtin[]>): string[] {
  const out: string[] = [];
  for (const [name, overloads] of Object.entries(table)) {
    for (const b of overloads) {
      const sig = `\`${name}(${b.slots.map(argName).join(", ")})\``;
      const where = b.spriteOnly ? "sprite" : "any";
      const returns = b.returns === "bool" ? " (boolean)" : "";
      out.push(`| ${sig} | ${b.doc.replace(/\|/g, "\\|")}${returns} | \`${b.opcode}\` | ${where} |`);
    }
  }
  return out;
}

export function renderBuiltins(): string {
  const header = ["| Pseudocode | Scratch block | Opcode | Where |", "| --- | --- | --- | --- |"];
  return [
    BEGIN,
    "",
    "#### Statements",
    "",
    ...header,
    ...rows(STATEMENTS),
    "",
    "#### Reporters",
    "",
    ...header,
    ...rows(REPORTERS),
    "",
    END,
  ].join("\n");
}

export function updatedDoc(doc: string): string {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < 0) throw new Error(`docs/pseudocode.md is missing the ${BEGIN} / ${END} markers`);
  return doc.slice(0, start) + renderBuiltins() + doc.slice(end + END.length);
}

// ---- docs/blocks.md ----

const STATUS = { compiled: "Compiled", partial: "Partial", missing: "Missing" } as const;

function kind(spec: BlockSpec): string {
  switch (spec.kind) {
    case "statement":
      if (spec.yields === "wait") return "statement, waits";
      if (spec.yields === "loop") return "loop";
      return spec.substacks?.length ? "statement, nests" : "statement";
    case "hat":
      if (spec.definesProcedure) return "hat, defines a block";
      if (spec.edgeActivated) return "hat, edge-triggered";
      return spec.restartExistingThreads ? "hat, restarts" : "hat, no restart";
    case "menu":
      return `menu (\`${spec.field}\`)`;
    default:
      return spec.kind;
  }
}

function counts(specs: BlockSpec[]): Record<keyof typeof STATUS, number> {
  const n = { compiled: 0, partial: 0, missing: 0 };
  for (const spec of specs) n[spec.status]++;
  return n;
}

/** Blocks that count toward coverage: every opcode but the menus, which the compiler resolves for any block. */
const counted = (e: Extension) => Object.values(e.blocks).filter((s) => s.kind !== "menu");

export function renderBlocksDoc(extensions: readonly Extension[] = BUILTIN_EXTENSIONS): string {
  const out = [
    "# Block coverage",
    "",
    "<!-- Generated by `pnpm run docs` from packages/compiler/src/extensions/; do not edit by hand. -->",
    "",
    "Every opcode TurboWarp knows, by the extension that declares it (see [extensions.md](extensions.md)),",
    "with how far Bytecat compiles it. **Compiled** matches TurboWarp, **Partial** compiles but differs",
    "in a case real projects reach, and **Missing** is reported as an unsupported block.",
    "`tests/inventory.test.ts` fails when TurboWarp knows an opcode that is not listed here, or when a",
    "status disagrees with the compiler's handlers.",
    "",
    "## Summary",
    "",
    "Palette blocks only; hidden ones (Scratch 2 leftovers and TurboWarp extras) and menus are listed",
    "below but not counted.",
    "",
    "| Extension | Id | Compiled | Partial | Missing |",
    "| --- | --- | --- | --- | --- |",
  ];
  const total = { compiled: 0, partial: 0, missing: 0 };
  for (const e of extensions) {
    const n = counts(counted(e).filter((s) => !s.hidden));
    for (const k of Object.keys(total) as (keyof typeof total)[]) total[k] += n[k];
    out.push(`| [${e.name}](#${e.id}) | \`${e.id}\` | ${n.compiled} | ${n.partial} | ${n.missing} |`);
  }
  out.push(`| **All** | | **${total.compiled}** | **${total.partial}** | **${total.missing}** |`);
  for (const e of extensions) {
    const n = counts(counted(e));
    out.push(
      "",
      `<a id="${e.id}"></a>`,
      "",
      `## ${e.name} (\`${e.id}\`)`,
      "",
      `${n.compiled} compiled, ${n.partial} partial, ${n.missing} missing, counting hidden blocks.`,
      "",
      "| Opcode | Kind | Status | Palette | Notes |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const [opcode, spec] of Object.entries(e.blocks)) {
      const note = (spec.note ?? "").replace(/\|/g, "\\|");
      out.push(`| \`${opcode}\` | ${kind(spec)} | ${STATUS[spec.status]} | ${spec.hidden ? "hidden" : "yes"} | ${note} |`);
    }
  }
  return out.join("\n") + "\n";
}

if (process.argv[1]?.endsWith("gen-docs.ts")) {
  writeFileSync(DOC, updatedDoc(readFileSync(DOC, "utf8")));
  console.log("updated docs/pseudocode.md");
  writeFileSync(BLOCKS_DOC, renderBlocksDoc());
  console.log("updated docs/blocks.md");
}
